const FIELDS = ['tip', 'waist', 'tail', 'sidecut', 'tipTaper', 'tailTaper', 'boot', 'camber', 'tipHeight', 'tailHeight', 'contact', 'tipRocker', 'tailRocker', 'radius', 'weight'];

// Stock ids that differ from the custom model ids.
const ALIASES = {'praxis-slugger': 'slugger'};

// The chart row for one model at one length, or null when unpublished.
export function specAt(model, length) {
  const chart = charts[ALIASES[model] ?? model];
  const index = chart?.lengths.indexOf(Number(length)) ?? -1;
  if (index < 0) return null;
  const row = {length, chart: chart.chart, year: chart.year, weightNote: chart.weightNote};
  for (const field of FIELDS) row[field] = Array.isArray(chart[field]) ? chart[field][index] : chart[field];
  return row;
}

export const chartFor = model => charts[ALIASES[model] ?? model] ?? null;
export const chartLengths = model => chartFor(model)?.lengths ?? [];
